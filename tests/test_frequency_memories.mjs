import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

const source = await readFile(new URL('../web/frequency-memories.js', import.meta.url));
const {FrequencyMemories, samePair, memoryMarkerGroups} = await import('data:text/javascript;base64,' + source.toString('base64'));
const pair = (rx, offset = 0) => ({rx: 10489700000 + rx, tx: 2400200000 + rx + offset});
const [a, b, c, d, e] = [0, 10000, 20000, 30000, 40000].map(rx => pair(rx, 750));
const empty = {history: [], memories: [null, null, null]};

const store = new FrequencyMemories();
assert.equal(store.refine(1, null, a), false, 'Zoom before selecting a slot creates no entry');
store.record(1, a);
const redA = store.selection(1);
const fineA = {...a, rx: a.rx + 25};
assert(store.refine(1, redA, fineA, 1));
assert.deepEqual(store.receivers[1].history, [fineA], 'Zoom updates the selected fullband destination, without consuming another slot');
store.record(1, b);
const redB = store.selection(1);
assert.deepEqual(store.receivers[1].history, [b, fineA], 'A new fullband target preserves the previously refined pair');
assert.equal(store.refine(1, redA, e, 2), false, 'A late reply for an inactive slot must not change it');
store.record(1, c); store.record(1, d);
assert.deepEqual(store.receivers[1].history, [d, c, b], 'Red slots keep the three most recent fullband destinations');
store.record(1, b);
assert.deepEqual(store.receivers[1].history, [b, d, c], 'Revisiting an exact pair reuses its red slot');
assert(store.isActive(1, 'history', 0));
assert.equal(store.record(1, {rx: NaN, tx: 42}), false);

assert.equal(store.save(1, a), 'saved');
const blueA = store.selection(1);
assert(store.isActive(1, 'memories', 0));
const fineBlueRx = {...a, rx: a.rx + 50};
const fineBlueTx = {...fineBlueRx, tx: a.tx - 25};
const fineBlueBoth = {rx: fineBlueTx.rx + 25, tx: fineBlueTx.tx + 25};
const beforeRed = structuredClone(store.receivers[1].history);
assert(store.refine(1, blueA, fineBlueRx, 10));
assert(store.refine(1, blueA, fineBlueTx, 11));
assert(store.refine(1, blueA, fineBlueBoth, 12));
assert.deepEqual(store.receivers[1].memories, [fineBlueBoth, null, null], 'RX, TX and coupled zoom adjustments update the same blue slot');
assert.deepEqual(store.receivers[1].history, beforeRed, 'Refining blue leaves all red slots unchanged');
assert.equal(store.refine(1, blueA, fineBlueRx, 11), false, 'Out-of-order acknowledgements cannot roll back the latest refinement');
assert.equal(store.refine(1, blueA, fineBlueBoth, 13), false);
assert.equal(store.refine(1, blueA, {rx: -1, tx: 42}, 14), false);
assert.equal(store.save(1, b), 'saved'); assert.equal(store.save(1, c), 'saved');
assert.equal(store.save(1, d), 'full');
assert.deepEqual(store.receivers[1].memories, [fineBlueBoth, b, c], 'Full blue slots require explicit replacement');
assert.equal(store.save(1, fineBlueBoth), 'full');
assert(store.select(1, store.reference(1, 'memories', 0)));
store.record(1, e);
const redE = store.selection(1);
assert.equal(store.refine(1, blueA, d, 20), false);
assert(store.refine(1, redE, {...e, tx: e.tx + 25}, 21));
assert.deepEqual(store.receivers[1].memories, [fineBlueBoth, b, c], 'A fullband click switches zoom editing back to red');
assert.equal(store.save(1, d, 1), 'saved');
assert.deepEqual(store.receivers[1].memories, [fineBlueBoth, d, c]);
assert(store.isActive(1, 'memories', 1));
const recall = store.reference(1, 'memories', 0);
const beforeRecall = structuredClone(store.receivers[1]);
assert(store.select(1, recall));
assert.deepEqual(store.receivers[1], beforeRecall, 'Recalling a slot activates it without creating a red entry');
assert(store.refine(1, store.selection(1), a, 30));
assert.deepEqual(store.receivers[1].memories, [a, d, c]);
assert.equal(store.remove(1, 'memories', 1), true);
assert(store.isActive(1, 'memories', 0), 'Deleting another slot preserves the active reference');
const deleted = store.selection(1);
assert.equal(store.remove(1, 'memories', 0), true);
assert.equal(store.selection(1), null);
assert.equal(store.refine(1, deleted, b, 31), false, 'Late refinement cannot recreate a deleted slot');
assert.equal(store.save(1, e), 'saved');
assert.deepEqual(store.receivers[1].memories, [e, null, c]);

const beforeRx2 = structuredClone(store.receivers[1]);
store.record(2, b);store.refine(2, store.selection(2), {...b, tx: b.tx + 25});
assert.equal(store.save(2, a), 'saved');
store.refine(2, store.selection(2), {...a, rx: a.rx + 25});
assert.deepEqual(store.receivers[1], beforeRx2, 'RX1 and RX2 have independent active slots');
const restored = new FrequencyMemories(store.serialize());
assert.deepEqual(restored.receivers, store.receivers);
assert(restored.isActive(1, 'memories', 0) && restored.isActive(2, 'memories', 0), 'The selected color and slot survive reloading');
assert(restored.refine(2, restored.selection(2), d, 1));
for (const value of ['broken', 'null', '{}', '{"version":2}']) {
  const invalid = new FrequencyMemories(value);
  assert.deepEqual(invalid.receivers[1], empty); assert.equal(invalid.selection(1), null);
}
const legacy = new FrequencyMemories(JSON.stringify({version: 1, receivers: {1: {history: [a, a, {}, b, c, d], memories: [a, null, {rx: 1}]}}}));
assert.deepEqual(legacy.receivers[1], {history: [a, b, c], memories: [a, null, null]});
assert.equal(legacy.selection(1), null, 'Existing saved frequencies load without choosing an arbitrary edit target');

const convergence = new FrequencyMemories();
convergence.record(1, a);convergence.record(1, b);
assert(convergence.refine(1, convergence.selection(1), a));
assert.deepEqual(convergence.receivers[1].history, [a], 'Converging red entries merge, preserving the edited entry');
assert(convergence.isActive(1, 'history', 0));
convergence.save(1, a);convergence.save(1, b);
assert(convergence.refine(1, convergence.selection(1), a));
assert.deepEqual(convergence.receivers[1].memories, [a, a, null], 'Refining blue never deletes another fixed slot');
const duplicateRestore = new FrequencyMemories(convergence.serialize());
assert.deepEqual(duplicateRestore.receivers, convergence.receivers);
assert(duplicateRestore.isActive(1, 'memories', 1));
assert.equal(convergence.entries(1).length, 3, 'Identical red and blue pairs remain individually selectable');

const fork = new FrequencyMemories();
fork.save(1, a);fork.save(1, a);
assert(fork.isActive(1, 'memories', 1), 'Another Save always selects the next free blue slot, even from the same starting frequency');
fork.refine(1, fork.selection(1), b);
assert.deepEqual(fork.receivers[1].memories, [a, b, null], 'Zoom after another Save edits the new slot and preserves the first');

const entries = [a, {...a, tx: a.tx + 10}, pair(100), c, pair(1000000)].map((pair, index) => ({kind: 'history', index, pair}));
const groups = memoryMarkerGroups(entries, 10489750000, 600000, 1000);
assert.deepEqual(groups.map(group => group.entries.length), [3, 1]);
assert(groups[0].entries[2].x > groups[0].entries[0].x);
assert.deepEqual(memoryMarkerGroups(entries, undefined, 600000, 1000), []);
assert(samePair(a, {...a}));
console.log('Frequency memories: target recording, active red/blue zoom refinement, reply ordering, RX isolation, deletion, recall and persistence passed.');
