"""Golden recording/FEC and UDP continuity regressions for the RX4 beacon trial."""
from pathlib import Path
import sys
import unittest
import warnings

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'decoder'))
import beacon_decoder as beacon
import numpy as np
from scipy import signal
from scipy.io import wavfile


def recording12():
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', wavfile.WavFileWarning)
        rate, pcm = wavfile.read(ROOT / 'external/qo100-beacon-decoder/sample.wav')
    pcm = signal.resample_poly(pcm.astype(float), 3, 2)
    # Move the recording's nominal 1500-Hz carrier to the user's RX4 dial (1179 Hz).
    pcm = np.real(signal.hilbert(pcm) * np.exp(-2j * np.pi * 321 * np.arange(len(pcm)) / 12000))
    return np.clip(np.rint(pcm), -32768, 32767).astype(np.int16)


class BeaconTests(unittest.TestCase):
    def test_recording(self):
        with warnings.catch_warnings():
            warnings.simplefilter('ignore', wavfile.WavFileWarning)
            rate, pcm = wavfile.read(ROOT / 'external/qo100-beacon-decoder/sample.wav')
        original, carrier = beacon.decode_audio(pcm, rate, 10489748500)
        self.assertEqual([sum(f.kind == k for f in original) for k in ('CRC', 'FEC')], [6, 5])
        self.assertAlmostEqual(carrier, 1506.14, delta=.5)
        shifted, carrier12 = beacon.decode_audio(recording12(), 12000, 10489748821)
        self.assertEqual([(f.kind, f.payload) for f in shifted], [(f.kind, f.payload) for f in original])
        self.assertAlmostEqual(carrier12, carrier - 321, delta=.05)
        # FEC repeats the first four lines of the preceding uncoded message.
        for index, frame in enumerate(original):
            if frame.kind == 'FEC':
                self.assertEqual(frame.payload, original[index-1].payload[:256])

    def test_rs_error_correction(self):
        # Independent GNU Radio test vector, not generated by this implementation.
        data = ROOT / 'tests/data/beacon'
        fec = beacon.reference.ao40_fec
        bits = (np.fromfile(data/'ao40_frame.f32', dtype='<f4') > 0).astype(np.uint8)
        post = np.packbits(fec.viterbi_decode(fec.deinterleave(bits)))
        self.assertEqual(bytes(post), (data/'post_viterbi.bin').read_bytes())
        expected = (data/'payload.bin').read_bytes()
        descrambled = post ^ fec.ccsds_sequence(320)
        self.assertEqual(fec.decode_fec_frame(bits), (expected, 0))
        for errors in (1, 8, 16):
            damaged = descrambled.copy()
            for word in (0, 1):
                for n in range(errors):
                    damaged[2 * (n * 9) + word] ^= 37 + n
            self.assertEqual(fec.rs_decode_frame(damaged), (expected, 2 * errors))
        self.assertEqual(bytes(fec.ccsds_sequence(8)).hex(), 'ff480ec09a0d70bc')

    def test_udp_continuity(self):
        buffer = beacon.AudioBuffer()
        peer = ('127.0.0.1', 40911)
        def packet(index, frequency=10489748821, epoch=7, session=99):
            return beacon.HEADER.pack(b'QTR2', 1, 5, 64, 6, epoch, 0, index, frequency,
                                      12000, 0, 0, 240, 2, 240, session) + bytes(480)
        buffer.push(b'invalid', peer)
        wrong = bytearray(packet(0)); wrong[8:12] = (2).to_bytes(4, 'big')
        buffer.push(bytes(wrong), peer)
        self.assertEqual(buffer.generation, 0, 'RX2 must not reach the PSK decoder')
        buffer.push(packet(0), ('192.168.1.2', 40911))
        self.assertEqual(buffer.generation, 0)
        buffer.push(packet(0), peer)
        generation = buffer.generation
        buffer.push(packet(0), peer)
        self.assertEqual(len(buffer.chunks), 1)
        for i in range(1, 1000):
            job = buffer.push(packet(i * 240), peer)
        self.assertEqual(job[0], generation)
        self.assertEqual(len(job[-1]), 20 * 12000)
        # Missing packet, soft retune (same epoch), session restart: all invalidate.
        buffer.push(packet(1001 * 240), peer)
        self.assertEqual(buffer.generation, generation + 1)
        buffer.push(packet(1002 * 240, frequency=10489748500), peer)
        self.assertEqual(buffer.generation, generation + 2)
        buffer.push(packet(0, session=100), peer)
        self.assertEqual(buffer.generation, generation + 3)
        self.assertEqual(len(buffer.chunks), 1)


if __name__ == '__main__':
    unittest.main()
